const imageUrl = (photoId) => `https://images.unsplash.com/photo-${photoId}?auto=format&fit=crop&q=80&w=1080`;

const formatKztPrice = (value) => `${Number(value || 0).toLocaleString("en-US")} KZT`;

const parsePriceValue = (value) => {
  if (Number.isFinite(Number(value))) return Number(value);
  const digits = String(value || "").replace(/\D/g, "");
  return Number(digits || 0);
};

const lowestPositivePrice = (values) => {
  const prices = values.map(parsePriceValue).filter((value) => value > 0);
  return prices.length ? Math.min(...prices) : 0;
};

const getSeedDisplayPrice = (item, eventType) => {
  const candidates =
    eventType === "special-program"
      ? [item.fullPassPrice, item.ticketPricing?.fullEventPass, ...(item.activities || []).map((item) => item.price)]
      : [item.ticketPricing?.generalAdmission, item.price];
  const lowest = lowestPositivePrice(candidates);
  return lowest ? formatKztPrice(lowest) : item.price;
};

